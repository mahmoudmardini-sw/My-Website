const LANG_STORAGE_KEY = "mm-lang";

function resolveLanguage() {
  try {
    const queryLang = new URLSearchParams(window.location.search).get("lang");
    if (queryLang && I18N[queryLang]) return queryLang;
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && I18N[saved]) return saved;
  } catch (error) {
    /* storage may be unavailable */
  }
  const browserLang = (navigator.language || "en").slice(0, 2).toLowerCase();
  return I18N[browserLang] ? browserLang : "en";
}

function applyLanguage(lang) {
  const safeLang = I18N[lang] ? lang : "en";
  const dictionary = I18N[safeLang];
  const fallback = I18N.en;

  document.documentElement.lang = safeLang;
  document.documentElement.dir = safeLang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    const value = dictionary[key] !== undefined ? dictionary[key] : fallback[key];
    if (value !== undefined) {
      element.textContent = value.replace("{YEAR}", new Date().getFullYear());
    }
  });

  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    const key = element.getAttribute("data-i18n-content");
    const value = dictionary[key] !== undefined ? dictionary[key] : fallback[key];
    if (value !== undefined) element.setAttribute("content", value);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const key = element.getAttribute("data-i18n-aria");
    const value = dictionary[key] !== undefined ? dictionary[key] : fallback[key];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });

  const selector = document.getElementById("langSelect");
  if (selector && selector.value !== safeLang) selector.value = safeLang;

  window.dispatchEvent(new CustomEvent("languagechange", { detail: { lang: safeLang } }));
  return safeLang;
}

function setLanguage(lang) {
  const applied = applyLanguage(lang);
  try {
    localStorage.setItem(LANG_STORAGE_KEY, applied);
  } catch (error) {
    /* ignore */
  }
  try {
    const url = new URL(window.location.href);
    if (url.searchParams.has("lang")) {
      url.searchParams.set("lang", applied);
      window.history.replaceState(window.history.state, "", url);
    }
  } catch (error) {
    /* history may be unavailable */
  }
  return applied;
}

window.I18N = I18N;
window.applyLanguage = applyLanguage;
window.setLanguage = setLanguage;

const langSelector = document.getElementById("langSelect");
if (langSelector) {
  langSelector.addEventListener("change", (event) => setLanguage(event.target.value));
}

applyLanguage(resolveLanguage());
